#!/usr/bin/env python3
"""Write view/src/PxFontData.inc from the firmware's pixel fonts (firmware/main/fonts/*.txt), the faces the
Samplooler's screen and the app letter with. Run it after a glyph changes:

    python3 rig/view/tools/gen_pxfont.py

It reads the fonts with the repo's own tools/fontconv.py parser.
"""
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
FONTS = os.path.join(ROOT, 'firmware', 'main', 'fonts')
OUT = os.path.join(HERE, '..', 'src', 'PxFontData.inc')
FACES = ['tiny', 'small', 'med', 'big']


def fontconv():
    spec = importlib.util.spec_from_file_location('fontconv', os.path.join(ROOT, 'tools', 'fontconv.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main():
    fc = fontconv()
    out = ['// Generated by rig/view/tools/gen_pxfont.py from firmware/main/fonts/*.txt. Do not edit.',
           '// Each glyph: its rows, top first; bit (w - 1 - c) of a row is column c.', '']
    faces = []
    for name in FACES:
        kind, f = fc.parse(os.path.join(FONTS, name + '.txt'))
        assert kind == 'font'
        h = f['height']
        rows, glyphs = [], []
        for code in sorted(f['glyphs']):
            art = f['glyphs'][code]
            w = len(art[0])
            glyphs.append((code, w, len(rows)))
            for r in art:
                rows.append(sum(1 << (w - 1 - c) for c, ch in enumerate(r) if ch == '#'))
        out.append(f'static const uint32_t PX_{name}_rows[{len(rows)}] = {{')
        for k in range(0, len(rows), 12):
            out.append('    ' + ', '.join(f'0x{v:x}' for v in rows[k:k + 12]) + ',')
        out.append('};')
        out.append(f'static const PxGlyphData PX_{name}_glyphs[{len(glyphs)}] = {{')
        for k in range(0, len(glyphs), 6):
            out.append('    ' + ' '.join(f'{{0x{c:02x}, {w}, {o}}},' for c, w, o in glyphs[k:k + 6]))
        out.append('};')
        kern = f['kern'] or [(0, 0, 0)]
        out.append(f'static const PxKernData PX_{name}_kern[{len(kern)}] = {{')
        out.append('    ' + ' '.join(f'{{0x{a:02x}, 0x{b:02x}, {d}}},' for a, b, d in kern))
        out.append('};')
        out.append('')
        faces.append(f'    {{"{name}", {h}, {f.get("cap") or h}, {f["spacing"]}, {f["space"]}, '
                     f'{"true" if "upper" in f["flags"] else "false"}, PX_{name}_glyphs, {len(glyphs)}, '
                     f'PX_{name}_rows, PX_{name}_kern, {len(f["kern"])}}},')
    out.append(f'static const PxFaceData PX_FACES[{len(FACES)}] = {{')
    out += faces
    out.append('};')
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    print(f'wrote {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
