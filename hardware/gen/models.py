"""Simple VRML bodies for the breakout modules, so the 3D view and renders show the build.

Coordinates are written in the footprint frame (mm, +X right, +Y down, origin at pad 1,
Z up from the carrier's top surface) and converted to VRML's Y-up. KiCad reads VRML in
units of 0.1 inch, so footprints load these with scale 1/2.54.
Heights: every module sits on 2.5 mm of header plastic.
"""
import math

HDR = 2.5
COL = {
    'black': (0.05, 0.05, 0.05), 'pcb_blue': (0.07, 0.17, 0.45), 'pcb_purple': (0.42, 0.12, 0.55),
    'pcb_black': (0.08, 0.08, 0.09), 'pcb_ss': (0.10, 0.28, 0.62), 'silver': (0.55, 0.56, 0.58),
    'gold': (0.85, 0.68, 0.25), 'chip': (0.12, 0.12, 0.13), 'glass': (0.02, 0.03, 0.05),
    'screen': (0.05, 0.25, 0.45), 'white': (0.9, 0.9, 0.88), 'cap': (0.1, 0.1, 0.1),
}


class Model:
    def __init__(self):
        self.shapes = []

    def box(self, x0, y0, x1, y1, z0, z1, color, shine=0.2):
        cx, cy, cz = (x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2
        self.shapes.append(('box', (cx, -cy, cz), (abs(x1 - x0), abs(y1 - y0), abs(z1 - z0)), color, shine))

    def cyl(self, cx, cy, r, z0, z1, color, axis='z', shine=0.3):
        """axis 'z': vertical, z0..z1. axis 'y': a barrel along the footprint Y centred on cy,
        z0..z1 then only give its height centre and length (z1 - z0)."""
        self.shapes.append(('cyl', (cx, -cy, (z0 + z1) / 2), (r, abs(z1 - z0)), color, shine, axis))

    def header(self, pins, z_pcb_top):
        """Header plastic under the module and gold tips above it, one per pin (x, y)."""
        for x, y in pins:
            self.box(x - 1.27, y - 1.27, x + 1.27, y + 1.27, 0, HDR, 'black', 0.1)
            self.box(x - 0.32, y - 0.32, x + 0.32, y + 0.32, z_pcb_top, z_pcb_top + 1.4, 'gold', 0.8)

    def vrml(self):
        out = ['#VRML V2.0 utf8', '# samplooler module body, generated by hardware/gen/models.py']
        for s in self.shapes:
            kind = s[0]
            color, shine = COL[s[3]], s[4]
            mat = (f'appearance Appearance {{ material Material {{ diffuseColor {color[0]} {color[1]} {color[2]} '
                   f'specularColor {shine:.2f} {shine:.2f} {shine:.2f} shininess {shine:.2f} }} }}')
            (x, y, z) = s[1]
            # VRML: X right, Y up, Z toward the viewer -> map our (x, -y, z) to (x, z?, ...): KiCad's
            # 3D frame is X right, Y "north", Z up, which VRML files express directly as X, Y, Z.
            if kind == 'box':
                sx, sy, sz = s[2]
                out.append(f'Transform {{ translation {x:.3f} {y:.3f} {z:.3f} children [ Shape {{ {mat} '
                           f'geometry Box {{ size {sx:.3f} {sy:.3f} {sz:.3f} }} }} ] }}')
            else:     # KiCad's VRML reader has no Cylinder node: emit a 32-sided prism
                r, h = s[2]
                axis = s[5]
                n = 32
                pts = []
                for end in (-h / 2, h / 2):
                    for i in range(n):
                        a = 2 * math.pi * i / n
                        u, v = r * math.cos(a), r * math.sin(a)
                        pts.append((x + u, y + v, z + end) if axis == 'z' else (x + u, y + end, z + v))
                faces = [f'{i} {(i + 1) % n} {n + (i + 1) % n} {n + i} -1' for i in range(n)]
                faces.append(' '.join(str(i) for i in reversed(range(n))) + ' -1')
                faces.append(' '.join(str(n + i) for i in range(n)) + ' -1')
                pl = ', '.join(f'{p[0]:.3f} {p[1]:.3f} {p[2]:.3f}' for p in pts)
                out.append(f'Shape {{ {mat} geometry IndexedFaceSet {{ solid FALSE creaseAngle 0.8 '
                           f'coord Coordinate {{ point [ {pl} ] }} coordIndex [ {" ".join(faces)} ] }} }}')
        return '\n'.join(out) + '\n'


def supermini(M):
    m = Model()
    row = M.SM_ROW
    top = HDR + 1.0
    m.header([(0, 2.54 * i) for i in range(9)] + [(row, 2.54 * i) for i in range(9)], top)
    m.box(-1.38, -1.59, row + 1.38, 21.91, HDR, top, 'pcb_black')
    m.box(row / 2 - 3.5, 8.0, row / 2 + 3.5, 15.0, top, top + 0.9, 'chip')          # ESP32-S3
    m.box(row / 2 - 4.5, -3.6, row / 2 + 4.5, 3.7, top, top + 3.2, 'silver', 0.9)   # USB-C
    for bx in (3.1, row - 3.1):                                                       # BOOT, RST
        m.box(bx - 1.5, 6.0, bx + 1.5, 8.0, top, top + 0.8, 'silver', 0.7)
        m.cyl(bx, 7.0, 0.5, top + 0.8, top + 1.2, 'black')
    m.box(2.1, 19.9, 8.2, 21.9, top, top + 0.8, 'white')                              # chip antenna
    m.box(row - 2.6, 15.3, row - 0.6, 17.3, top, top + 0.6, 'white')                  # RGB LED
    for _, x, y, _ in M.SUPERMINI.get('pogo', ()):                                     # pogo pins
        m.box(x - 0.67, y - 0.67, x + 0.67, y + 0.67, 0, 0.6, 'gold', 0.8)
        m.cyl(x, y, 0.35, 0.6, HDR, 'gold', shine=0.8)
    return m


def pcm5102(M):
    m = Model()
    top = HDR + 1.6
    m.header([(0, 2.54 * i) for i in range(6)] + [(M.DAC_ROW_X + 2.54 * i, M.DAC_ROW_Y) for i in range(9)], top)
    m.box(-1.5, -2.15, 30.2, 14.85, HDR, top, 'pcb_purple')
    m.box(9.5, 3.8, 16.0, 8.2, top, top + 1.0, 'chip')                                 # PCM5102A
    m.box(4.0, 9.5, 7.0, 11.5, top, top + 1.2, 'chip')                                 # LDO
    m.box(21.5, 2.4, 27.5, 14.8, top, top + 5.5, 'black', 0.15)                        # jack body
    m.cyl(24.5, 15.55, 2.6, top + 2.75 - 0.75, top + 2.75 + 0.75, 'silver', axis='y', shine=0.8)  # nose
    return m


def inmp441(M):
    m = Model()
    top = HDR + 1.0
    m.header([(-2.54, -3.81), (0, -3.81), (2.54, -3.81), (-2.54, 3.81), (0, 3.81), (2.54, 3.81)], top)
